#!/usr/bin/env node
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

function main() {
  const args = process.argv.slice(2);
  const problemIndex = args.indexOf('--problem');
  const skipRun = args.includes('--latest');

  if (args.includes('--help') || (problemIndex === -1 && !skipRun)) {
    console.log('Usage: node city-voice-demo.js --problem "question" [--latest]');
    console.log('  --problem "..."  Run city-voice on this problem then format');
    console.log('  --latest         Format the most recent voice artifact (skip run)');
    process.exit(problemIndex === -1 && !skipRun ? 1 : 0);
  }

  const problem = problemIndex !== -1 ? args[problemIndex + 1] : '(latest artifact)';

  // Run city-voice.js unless --latest
  if (!skipRun) {
    try {
      execSync('node .fastops/city-voice.js --problem ' + JSON.stringify(problem), { stdio: 'pipe' });
    } catch (e) { /* may exit non-zero but still produce output */ }
  }

  // Find latest voice artifact
  const voiceFiles = fs.readdirSync('.fastops')
    .filter(function(f) { return f.startsWith('_voice-') && f.endsWith('.json'); })
    .sort().reverse();

  if (voiceFiles.length === 0) { console.error('No voice artifact found'); process.exit(1); }

  var data;
  try { data = JSON.parse(fs.readFileSync(path.join('.fastops', voiceFiles[0]), 'utf8')); }
  catch (e) { console.error('Parse error:', e.message); process.exit(1); }

  // Extract from actual city-voice artifact structure
  var coreVoice = data.coreVoice || '';
  var divergenceReport = data.divergenceReport || '';
  var score = data.convergenceScore || 0;
  var convergedN = data.convergedClaims || 0;
  var divergedN = data.divergentClaims || 0;
  var models = data.models || [];

  // Parse bullet lines
  var agreements = coreVoice.split('\n').map(function(l) { return l.trim(); })
    .filter(function(l) { return l.startsWith('-'); })
    .map(function(l) { return l.replace(/^-\s*/, ''); });
  var disagreements = divergenceReport.split('\n').map(function(l) { return l.trim(); })
    .filter(function(l) { return l.startsWith('-'); })
    .map(function(l) { return l.replace(/^-\s*/, ''); });

  // Format presentation output
  var lines = [];
  lines.push('# CITY VOICE: ' + (data.problem || problem));
  lines.push('');
  lines.push('**Convergence: ' + (score * 100).toFixed(1) + '%** | ' + models.length + ' models | ' + convergedN + ' agreed | ' + divergedN + ' diverged');
  lines.push('');
  lines.push('## EXECUTIVE SUMMARY');
  if (agreements.length > 0) {
    agreements.slice(0, 7).forEach(function(a) { lines.push('- ' + a); });
  } else {
    lines.push('- No converged claims extracted');
  }
  lines.push('');
  lines.push('## KEY DISAGREEMENTS');
  if (disagreements.length > 0) {
    disagreements.slice(0, 5).forEach(function(d) { lines.push('- ' + d); });
  } else {
    lines.push('- Full convergence (no divergent claims)');
  }
  lines.push('');
  lines.push('## FULL CONVERGENCE MAP');
  lines.push(coreVoice.slice(0, 800));
  lines.push('');
  lines.push('## FULL DIVERGENCE MAP');
  lines.push(divergenceReport.slice(0, 800));
  lines.push('');
  lines.push('---');
  lines.push('_Generated by city-voice.js | ' + models.length + ' architectures | ' + new Date().toISOString().slice(0, 10) + '_');

  console.log(lines.join('\n'));
}

if (require.main === module) { main(); }
