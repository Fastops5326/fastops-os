#!/usr/bin/env node
/**
 * city-dawn-trigger.js — Nightly trigger for the city-dawn convergence cycle
 *
 * Scheduled via Windows Task Scheduler at 10 PM nightly.
 * This is the launcher that kicks off the full 5-wave cycle.
 *
 * Until city-dawn.js is fully wired, this runs the existing
 * infrastructure as a bridge:
 *   1. Collect state (git log, marketplace, ledger, uncommitted)
 *   2. Run city-pipeline convergence on "state of reality"
 *   3. Output daily-brief-YYYY-MM-DD.md
 *   4. Fire CDP wake for Cursor agents to QC
 *
 * Once city-dawn.js is built by Grok-Full, this becomes a thin
 * wrapper that calls city-dawn.js --run.
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const BASE = __dirname;
const today = new Date().toISOString().split('T')[0];
const briefPath = path.join(BASE, `daily-brief-${today}.md`);

console.log(`\n=== CITY DAWN TRIGGER — ${today} ===\n`);

// Check if city-dawn.js exists and is built
const dawnPath = path.join(BASE, 'city-dawn.js');
if (fs.existsSync(dawnPath)) {
  console.log('city-dawn.js found — delegating to full orchestrator...');
  try {
    const result = execSync(`node "${dawnPath}" --run`, {
      timeout: 3600000, // 1 hour max
      encoding: 'utf8',
      maxBuffer: 10 * 1024 * 1024,
      cwd: path.join(BASE, '..')
    });
    console.log(result);
    process.exit(0);
  } catch (e) {
    console.error(`city-dawn.js failed: ${e.message?.slice(0, 200)}`);
    console.log('Falling back to bridge mode...\n');
  }
}

// === BRIDGE MODE — until city-dawn.js is built ===

console.log('Running in BRIDGE mode (city-dawn.js not yet available)\n');

// Step 1: Collect state
console.log('Step 1: Collecting state...');
let stateSnapshot = '';

try {
  const gitLog = execSync('git log --oneline --since="24 hours ago" -20', {
    encoding: 'utf8', cwd: path.join(BASE, '..'), timeout: 10000
  }).trim();
  stateSnapshot += `## Git Activity (last 24h)\n${gitLog || 'No commits'}\n\n`;
} catch { stateSnapshot += '## Git Activity\nUnavailable\n\n'; }

try {
  const gitStatus = execSync('git status --short', {
    encoding: 'utf8', cwd: path.join(BASE, '..'), timeout: 10000
  }).trim();
  const lines = gitStatus.split('\n').filter(Boolean);
  stateSnapshot += `## Uncommitted Work\n${lines.length} files with uncommitted changes\n\n`;
} catch { stateSnapshot += '## Uncommitted Work\nUnavailable\n\n'; }

try {
  const marketplace = execSync(`node "${path.join(BASE, 'city-marketplace.js')}" --list`, {
    encoding: 'utf8', timeout: 10000
  }).trim();
  stateSnapshot += `## Open Marketplace Problems\n${marketplace}\n\n`;
} catch { stateSnapshot += '## Marketplace\nUnavailable\n\n'; }

try {
  const brief = execSync(`node "${path.join(BASE, 'city-brief.js')}" --oneliner`, {
    encoding: 'utf8', timeout: 30000
  }).trim();
  stateSnapshot += `## City Brief\n${brief}\n\n`;
} catch { stateSnapshot += '## City Brief\nUnavailable\n\n'; }

try {
  const ledger = execSync(`node "${path.join(BASE, 'city-ledger.js')}" --count`, {
    encoding: 'utf8', timeout: 10000
  }).trim();
  stateSnapshot += `## Ledger\n${ledger}\n\n`;
} catch {}

console.log(`  State collected: ${stateSnapshot.length} chars\n`);

// Step 2: Run convergence pipeline
console.log('Step 2: Running convergence pipeline...');
const question = `Here is the current state of FastOps as of ${today}:\n\n${stateSnapshot}\n\nAs a founding model of the FastOps City: What is the ground truth today? What structural fractures exist? What needs coordinated action? What did NO ONE address? Defend your position.`;

try {
  // Write question to temp file to avoid shell length limits (same pattern as city-dawn.js)
  const tmpQuestionFile = path.join(BASE, '.dawn-bridge-question-tmp.txt');
  fs.writeFileSync(tmpQuestionFile, question);
  const pipelineResult = execSync(
    `node "${path.join(BASE, 'city-pipeline.js')}" --problem-file "${tmpQuestionFile}" --fast`,
    { timeout: 600000, encoding: 'utf8', maxBuffer: 5 * 1024 * 1024, cwd: path.join(BASE, '..') }
  );
  try { fs.unlinkSync(tmpQuestionFile); } catch {}

  // Step 3: Write daily brief
  console.log('\nStep 3: Writing daily brief...');
  const briefContent = `# Daily Brief — ${today}\n\n**Generated by:** City Dawn (bridge mode)\n**Models:** city-pipeline.js convergence\n**Status:** PENDING APPROVAL\n\n---\n\n${pipelineResult}\n\n---\n\n## State Snapshot\n${stateSnapshot}\n\n---\n*Generated at ${new Date().toISOString()}*\n*Awaiting Joel approval. Run: node .fastops/city-brief-template.js --approve*\n`;

  fs.writeFileSync(briefPath, briefContent);
  console.log(`  Written: ${briefPath}\n`);

} catch (e) {
  console.error(`Pipeline failed: ${e.message?.slice(0, 200)}`);

  // Write a minimal brief with just the state snapshot
  const minBrief = `# Daily Brief — ${today}\n\n**Generated by:** City Dawn (bridge mode — pipeline failed)\n**Status:** NEEDS MANUAL REVIEW\n\n---\n\n## State Snapshot\n${stateSnapshot}\n\n---\n*Pipeline error: ${e.message?.slice(0, 100)}*\n*Generated at ${new Date().toISOString()}*\n`;

  fs.writeFileSync(briefPath, minBrief);
  console.log(`  Written minimal brief: ${briefPath}`);
}

// Step 4: Fire CDP wake
console.log('Step 4: Firing CDP wake for Cursor agents...');
try {
  const cdpWake = path.join(BASE, 'cdp', 'cdp-wake.js');
  if (fs.existsSync(cdpWake)) {
    execSync(`node "${cdpWake}" --message "CITY DAWN: Daily brief ready for QC at ${briefPath}"`, {
      timeout: 30000, encoding: 'utf8'
    });
    console.log('  CDP wake fired.\n');
  } else {
    console.log('  cdp-wake.js not found — skipping CDP wake.\n');
  }
} catch (e) {
  console.log(`  CDP wake failed: ${e.message?.slice(0, 80)}\n`);
}

// Step 5: Log to ledger
try {
  const CityLedger = require('./city-ledger');
  const ledger = new CityLedger();
  ledger.append({
    type: 'dawn',
    action: 'daily-brief-generated',
    data: { date: today, briefPath, mode: 'bridge' },
    tags: ['dawn', 'daily-brief', today]
  });
  console.log('  Logged to city ledger.');
} catch {}

console.log(`\n=== CITY DAWN COMPLETE — Brief at ${briefPath} ===\n`);
